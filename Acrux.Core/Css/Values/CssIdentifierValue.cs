    public CssValueId Id { get; }
    public string? RawValue { get; }

    private CssIdentifierValue(CssValueId id, string? rawValue) : base(CssClassType.Identifier)
    {
        Id = id;
        RawValue = rawValue;
    }

    public CssIdentifierValue(CssValueId id) : base(CssClassType.Identifier)
    {
        Id = id;
    }

    public static CssIdentifierValue Create(CssValueId id) => new(id);

    public override string CssText() => RawValue ?? ValueIdToString(Id);

    public override bool Equals(CssValue other) =>
        other is CssIdentifierValue v && Id == v.Id && RawValue == v.RawValue;

    public override int GetHashCode() => HashCode.Combine((int)Id, RawValue);

